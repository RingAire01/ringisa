"""Generate the SoC address constants and reference tables, without ISA changes."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
def main():
    spec=json.loads((ROOT/'spec/soc.json').read_text())
    regions=spec['regions'];ordered=sorted(regions,key=lambda r:r['base'])
    for i,r in enumerate(ordered):
        if r['base']%4096 or r['size']%4096 or not 0<r['size']<=1<<32 or r['base']+r['size']>1<<64:raise ValueError('invalid SoC region')
        if i and ordered[i-1]['base']+ordered[i-1]['size']>r['base']:raise ValueError('overlapping regions')
    lines=['// Generated by tools/specgen/soc.py','`ifndef RINGISA_SOC_MAP','`define RINGISA_SOC_MAP']
    docs=['# SoC address map (generated)','', '| Region | Physical base | Bytes | Writes |','|---|---|---|---|']
    for r in regions:
        lines += [f'`define SOC_{r["name"]}_BASE 64\'h{r["base"]:016x}',f'`define SOC_{r["name"]}_BYTES {r["size"]}']
        docs.append(f'| {r["name"]} | `0x{r["base"]:016x}` | {r["size"]} | {r["writable"]} |')
    for name,registers in spec['registers'].items():
        docs += ['',f'## {name}','', '| Register | Byte offset |','|---|---|']
        for reg,offset in registers.items():
            lines.append(f'`define SOC_{name}_{reg} 12\'h{offset:03x}');docs.append(f'| {reg} | `0x{offset:03x}` |')
    lines+=['`endif'];(ROOT/'rtl/soc').mkdir(exist_ok=True)
    (ROOT/'rtl/soc/map.svh').write_text('\n'.join(lines)+'\n',newline='\n')
    (ROOT/'docs/soc').mkdir(parents=True,exist_ok=True)
    (ROOT/'docs/soc/address-map.md').write_text('\n'.join(docs)+'\n',newline='\n')
    print('Validated SoC map; generated RTL constants and address reference')
if __name__=='__main__':main()

"""Validate the authoritative ISA and generate C/SV decoder metadata."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

def generate():
    spec = json.loads((ROOT / 'spec/isa.json').read_text())
    instructions = spec['instructions']
    required={'registers':64,'register_bits':256,'virtual_address_bits':128,'physical_address_bits':64,'instruction_alignment':4,'endianness':'little'}
    for key,value in required.items():
        if spec.get(key)!=value:raise ValueError(f'fixed architectural requirement violated: {key}')
    if spec['mmu']['levels']!=15 or spec['mmu']['vpn_bits']!=116 or spec['mmu']['pte_bits']!=128 or spec['mmu']['page_bytes']!=4096:
        raise ValueError('full128-bit MMU layout is mandatory')
    ops, names = set(), set()
    for ins in instructions:
        if not (0 < ins['op'] < 256 and ins['op'] not in ops):raise ValueError('invalid/colliding opcode')
        if ins['name'] in names or ins['format'] not in ('R', 'I', 'X'):raise ValueError('invalid instruction name/format')
        ops.add(ins['op']); names.add(ins['name'])
        if ins['name'] not in spec['semantics'] and ins['family'] not in spec['semantics']:raise ValueError('missing instruction semantics')
    header = ['/* Generated by tools/specgen/generate.py; do not edit. */',
              '#ifndef RINGISA_GENERATED_H', '#define RINGISA_GENERATED_H',
              'typedef struct { const char *name; unsigned char op, format, family; unsigned short bits; unsigned char sign; } ri_meta;',
              'enum { RI_PLAIN, RI_SCALAR, RI_SIMD, RI_LOAD, RI_STORE, RI_BRANCH, RI_SYSTEM };']
    definitions=['/* Generated; do not edit. */','#include "generated.h"','const ri_meta ri_instructions[RI_INSTRUCTION_COUNT] = {']
    header += [f'#define RI_PAGE_SIZE {spec["mmu"]["page_bytes"]}',f'#define RI_CSR_COUNT {len(spec["csrs"])}',
               'enum { '+','.join('RI_'+csr['name']+'='+str(csr['index']) for csr in spec['csrs'])+' };',
               'enum { '+','.join('RI_PTE_'+name+'='+str(1<<bit) for name,bit in spec['mmu']['flags'].items())+' };']
    sv = ['// Generated; included inside decoder case statement.']
    constants=['// Generated opcode constants.','`default_nettype none','`ifndef RINGISA_OPCODES_CONSTANTS','`define RINGISA_OPCODES_CONSTANTS']
    memory=['// Generated memory width and signed-extension decode.']
    for ins in instructions:
        ident = ins['name'].replace('.', '_')
        constants.append(f'`define RINGISA_{ident} 8\'d{ins["op"]}')
        header.insert(3, f'#define RI_{ident} {ins["op"]}')
        definitions.append('    {"%s", %d, \'%s\', RI_%s, %d, %d},' %
                      (ins['name'], ins['op'], ins['format'], ins['family'].upper(), ins.get('bits', 0), ins.get('signed', False)))
        func_limit = 6 if ins['family'] == 'scalar' else 4 if ins['family'] == 'simd' else 0
        sv.append(f"8'd{ins['op']}: begin valid = 1'b1; rtype = 1'b{int(ins['format']=='R')}; func_limit = 4'd{func_limit}; end")
        if ins['family'] in ('load','store'):
            memory.append(f"8'd{ins['op']}: begin byte_count=6'd{ins['bits']//8}; signed_load=1'b{int(ins.get('signed',False))}; end")
    definitions+=['};']
    header += [f'#define RI_INSTRUCTION_COUNT {len(instructions)}u','extern const ri_meta ri_instructions[RI_INSTRUCTION_COUNT];','#endif']
    (ROOT / 'tools/common').mkdir(parents=True, exist_ok=True)
    (ROOT / 'rtl/decode').mkdir(parents=True, exist_ok=True)
    (ROOT / 'tools/common/generated.h').write_text('\n'.join(header)+'\n')
    (ROOT / 'tools/common/generated.c').write_text('\n'.join(definitions)+'\n')
    (ROOT / 'rtl/decode/opcodes.svh').write_text('\n'.join(sv)+'\n')
    constants+=['`endif']
    (ROOT / 'rtl/decode/constants.svh').write_text('\n'.join(constants)+'\n')
    (ROOT / 'rtl/decode/memory.svh').write_text('\n'.join(memory)+'\n')
    docs=['# Generated instruction reference', '', 'Source: `spec/isa.json`. Do not edit this table manually.', '', '| OP | Mnemonic | Format | Exact behavior |','|---|---|---|---|']
    for ins in instructions:
        behavior=spec['semantics'].get(ins['name'],spec['semantics'].get(ins['family'],''))
        docs.append(f'| 0x{ins["op"]:02x} | {ins["name"]} | {ins["format"]} | {behavior} |')
    (ROOT/'docs').mkdir(exist_ok=True)
    (ROOT/'docs/instructions.md').write_text('\n'.join(docs)+'\n')
    print(f'validated {len(instructions)} unique opcodes; generated C and SV tables')

if __name__ == '__main__':
    generate()
